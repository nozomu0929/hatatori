export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** この文字を描けるか。描けない文字が混じるとフラグが読めなくなるため事前に確認する */
export function canRender(text: string): boolean {
  return [...text.toUpperCase()].every((c) => c in GLYPHS);
}

export function textWidth(text: string, scale = 1, spacing = 1): number {
  return text.length * (GLYPH_W + spacing) * scale;
}

/**
 * 画素バッファ(RGB)に文字を描く。
 * plot は 1画素を塗る処理で、呼び出し側が「色を変える」のか
 * 「最下位ビットだけ変える」のかを決められるようにしてある。
 */
export function drawText(
  text: string, x0: number, y0: number, scale: number,
  plot: (x: number, y: number) => void, spacing = 1,
): void {
  let cx = x0;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch];
    if (g) {
      const rows = g.split("/");
      for (let ry = 0; ry < rows.length; ry++) {
        for (let rx = 0; rx < rows[ry].length; rx++) {
          if (rows[ry][rx] !== "#") continue;
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              plot(cx + rx * scale + sx, y0 + ry * scale + sy);
            }
          }
        }
      }
    }
    cx += (GLYPH_W + spacing) * scale;
  }
}
